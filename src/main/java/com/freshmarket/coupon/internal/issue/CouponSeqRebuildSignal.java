package com.freshmarket.coupon.internal.issue;

/**
 * 플러시 스레드가 배치를 쓴 뒤 재건이 도는지 보는 자리다.
 *
 * <p>이 인터페이스가 있는 이유는 방향 때문이다. {@code issue} 패키지는 큐와 플러시를 갖고
 * {@code redis} 패키지가 그것을 읽어 재건한다. 플러시가 재건기를 직접 부르면 두 패키지가 서로를
 * 가리켜, <b>어느 쪽이 어느 쪽을 쓰는지가 흐려진다.</b>
 */
public interface CouponSeqRebuildSignal {

    /**
     * 방금 쓴 배치의 쿠폰이 재건 중인지 보고, 그렇다면 이 인스턴스의 큐를 올리게 한다.
     * 같은 자리에서 카운터가 뒤처지지 않았는지도 잰다.
     *
     * <p><b>부르는 쪽을 막지 않는다.</b> 실제 일은 다른 스레드가 한다. 여기서 큐를 얼리면
     * 플러시 스레드가 자기를 얼리는 셈이 된다.
     *
     * @param maxIssuedSeq 방금 쓴 배치에 든 가장 큰 순번. 카운터가 뒤처졌는지의 기준이 된다
     */
    void checkAfterFlush(long couponId, int maxIssuedSeq);

    /**
     * 이 인스턴스가 지금 큐를 쥐고 있다고 알린다. 플러시가 배치를 집은 직후에 부른다.
     *
     * <p><b>쓰기보다 먼저 부르는 것이 이 메서드의 존재 이유다.</b> 재건 주도자는 이 알림으로
     * 몇 대를 기다릴지 정하는데, 알림을 {@code flush} 뒤에 두면 DB 가 막힌 인스턴스가 배치를
     * 못 끝내 알림도 멈춘다. <b>그러면 큐를 쥐고 있는데도 명부에서 빠지고, 주도자가 그 큐를
     * 안 기다린 채 키를 세워 그 번호들을 남에게 다시 내준다.</b>
     *
     * <p>2026-09-22 회차에서 그렇게 됐다. DB 를 10초 막았더니 세 대가 모두 명부에서 빠졌고,
     * 셋이 다 올렸는데도 주도자가 그것을 모른 채 정해진 시간을 끝까지 기다렸다.
     */
    void holdingQueue();
}
