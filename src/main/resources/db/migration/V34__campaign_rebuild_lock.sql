-- =====================================================================
-- 캠페인 대상 확정 직렬화용 잠금 행(stock 도메인)
-- =====================================================================
-- 확정(자정 배치 + 관리자 재실행)을 한 번에 하나만 돌게 하는 것이 유일한 용도다.
-- 값을 담지 않는다 — 행 자체가 잠글 대상일 뿐이라 SELECT ... FOR UPDATE 로만 쓴다.
--
-- campaign_target_lot 을 직접 잠그지 않는 이유가 있다. 확정은 그날 행을 지우고 다시 넣는
-- 작업이라, 자정 직후처럼 그날 행이 아직 없으면 잠글 행 자체가 없다. 그때 DELETE 가 잡는 것은
-- 행 락이 아니라 구간(갭) 락인데, 갭 락끼리는 서로 충돌하지 않아 두 갈래가 나란히 통과한 뒤
-- INSERT 에서 교착이 난다. 항상 있는 행 하나를 먼저 잠그면 그 순환이 만들어지지 않는다.
--
-- 행을 여기서 심는다. 없으면 "먼저 넣고 잠근다" 가 되는데 그 INSERT 가 다시 경합 지점이 된다.
--
-- 기준일별로 나누지 않는다. 확정은 언제나 "오늘" 하나만 대상으로 하므로 동시에 살아 있어야 할
-- 잠금이 둘 이상이 될 일이 없다. 나누면 자정을 사이에 두고 두 날짜가 각자 잠겨 동시에 도는
-- 구멍이 생긴다.

CREATE TABLE campaign_rebuild_lock (
    lock_name VARCHAR(50) NOT NULL, -- 잠금 이름. 지금은 하나뿐이라 값도 하나다
    PRIMARY KEY (lock_name)
); -- 캠페인 대상 확정을 한 번에 하나만 돌게 하는 잠금 행

INSERT INTO campaign_rebuild_lock (lock_name) VALUES ('campaign_target_lot');
